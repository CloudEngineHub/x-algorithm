#[derive(Clone, Copy)]
pub(crate) struct PostRules {
    pub(super) user: &'static [&'static UserRule],
    pub(super) post: &'static [&'static Rule],
}

#[derive(Clone, Copy)]
pub(crate) enum LevelRules {
    UserOnly(&'static [&'static UserRule]),
    UserThenPost(PostRules),
}

impl LevelRules {
    pub(super) const fn lists(self) -> PostRules {
        match self {
            Self::UserOnly(user) => PostRules { user, post: &[] },
            Self::UserThenPost(rules) => rules,
        }
    }
}

